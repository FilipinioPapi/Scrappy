// Posters for the made-for-you playlists (approved mock "Made-for-you playlists", option A):
// Your top 50 of <year>, Favorite songs, Most played, Recently added. Pure CSS art that scales
// with its box, so the same poster works on a card, the playlist page and the side menu.
const ic = (d, sw = 1.7) => `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${d}</svg>`;
const HEART = '<path d="M12 20s-7-4.5-7-10a4 4 0 0 1 7-2.6A4 4 0 0 1 19 10c0 5.5-7 10-7 10z"/>';
const FLAME = '<path d="M12 3c1 3.5 5 5.5 5 10a5 5 0 0 1-10 0c0-2.5 1.5-4 2.5-5 .3 1.6 1 2.6 2 3 0-3 .5-5.5.5-8z"/>';

/** kind: 'year' | 'fav' | 'most' | 'new'. cls: extra classes ('big' on the playlist page). */
export function autoArt(kind, { year = '', cls = '' } = {}) {
  let inner = '';
  if (kind === 'year') {
    inner = `<em class="ap-yr">${year}</em><b class="ap-pill">TOP 50</b>
      <i class="ap-eq">${[10, 18, 26, 14, 22, 30, 16, 24].map((h) => `<i style="height:${h / 30 * 100}%"></i>`).join('')}</i>
      <b class="ap-t">Your<br>top 50</b>`;
  } else if (kind === 'fav') {
    inner = `<i class="ap-bigheart">${ic(HEART, 1.4)}</i>
      ${[[67, 8, 14, 12], [81, 30, 9, -10], [58, 36, 8, 20], [83, 56, 11, 8]].map(([x, y, s, r], k) => `<i class="ap-hrt" style="left:${x}%;top:${y}%;width:${s}%;transform:rotate(${r}deg);opacity:${[0.9, 0.6, 0.45, 0.5][k]}">${ic(HEART, 1.8)}</i>`).join('')}
      <b class="ap-t ap-bottom">Favorite<br>songs</b>`;
  } else if (kind === 'most') {
    inner = `<i class="ap-bars">${[30, 48, 40, 70, 58, 96].map((h) => `<i style="height:${h}%"></i>`).join('')}</i>
      <i class="ap-flame">${ic(FLAME, 1.8)}</i><b class="ap-t">Most<br>played</b>`;
  } else {
    inner = `<i class="ap-rec" style="left:39%;top:34%"><i style="background:#FF6B8B"></i></i><i class="ap-rec" style="left:49%;top:22%"><i style="background:#FFD678"></i></i>
      <b class="ap-stk">NEW</b><b class="ap-t">Recently<br>added</b>`;
  }
  return `<div class="mcv apost ap-${kind} ${cls}">${inner}</div>`;
}

/** Scrappy's yearly top-50 playlist: "Your top 50 of 2026" (older builds named it "Your 2026"). */
export function yearOf(p) {
  if (!p || !String(p.comment || '').includes('Generated by Scrappy')) return '';
  const m = /^Your (?:top 50 of )?(\d{4})$/.exec(p.name || '');
  return m ? m[1] : '';
}
export const yearName = (y) => `Your top 50 of ${y}`;
/** Which poster an auto playlist id uses. */
export const autoKind = (id) => ({ 'auto:fav': 'fav', 'auto:most': 'most', 'auto:new': 'new' }[id] || '');
